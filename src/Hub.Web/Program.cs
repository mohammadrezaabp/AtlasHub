using Hub.Infrastructure;
using Hub.Infrastructure.Persistence;
using Hub.Web.Components;
using Hub.Web.Endpoints;
using Hub.Web.Middleware;
using Hub.Web.Security;
using Hub.Web.Workers;

var builder = WebApplication.CreateBuilder(args);
builder.AddHubInfrastructure("atlas-knowledge-hub");
builder.AddRealtimeDelivery();
builder.Services.AddRazorComponents();
builder.Services.AddHostedService<AgentWorker>();
builder.AddWebSecurity();
var app = builder.Build();
await DatabaseInitializer.InitializeAsync(app.Services);
await app.Services.GetRequiredService<IdentityService>().Bootstrap(app.Configuration["Bootstrap:Email"] ?? "admin@atlas.local", app.Configuration["Bootstrap:Password"] ?? "");
await app.Services.GetRequiredService<IStorageMaintenance>().Migrate();
app.UseMiddleware<SecurityHeadersMiddleware>();
app.UseMiddleware<ApiExceptionMiddleware>();
app.UseStaticFiles();
app.UseAuthentication();
app.UseAuthorization();
app.UseRateLimiter();
app.UseAntiforgery();
app.UseMiddleware<ApiAntiforgeryMiddleware>();
OperationalEndpoints.Map(app);
AuthEndpoints.MapPublic(app);
var api = app.MapGroup("/api").RequireAuthorization().RequireRateLimiting("user");
AuthEndpoints.Map(api);
DocumentEndpoints.Map(api);
ConversationEndpoints.Map(api);
WorkspaceEndpoints.Map(api);
AdminEndpoints.Map(api);
SpeechEndpoints.Map(api);
RealtimeEndpoints.Map(api);
app.MapRazorComponents<App>();
app.Run();
